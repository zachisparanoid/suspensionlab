/** Params in a category, non-advanced first. `roadInput` is excluded (custom control). */
export function paramsForCategory(cat: ParamCategory): ParamMeta[] {
  return Object.values(PARAM_META)
    .filter((m) => m.category === cat && m.key !== 'roadInput')
    .sort((a, b) => Number(a.advanced ?? false) - Number(b.advanced ?? false));
}
